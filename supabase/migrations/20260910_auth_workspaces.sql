create policy "profiles_select_self_or_platform_admin"
on public.profiles for select
to authenticated
using ((select auth.uid()) = id or private.is_platform_admin());

create policy "profiles_update_self"
on public.profiles for update
to authenticated
using ((select auth.uid()) = id)
with check ((select auth.uid()) = id);

create policy "members_select_self_or_platform_admin"
on public.workspace_members for select
to authenticated
using (user_id = (select auth.uid()) or private.is_platform_admin());

create policy "workspaces_select_member_or_platform_admin"
on public.workspaces for select
to authenticated
using (
  private.is_platform_admin()
  or exists (
    select 1 from public.workspace_members wm
    where wm.workspace_id = workspaces.id
      and wm.user_id = (select auth.uid())
      and wm.status = 'active'
  )
);

create policy "workspaces_insert_owner"
on public.workspaces for insert
to authenticated
with check (owner_id = (select auth.uid()) or private.is_platform_admin());

create policy "workspaces_update_owner_or_platform_admin"
on public.workspaces for update
to authenticated
using (owner_id = (select auth.uid()) or private.is_platform_admin())
with check (owner_id = (select auth.uid()) or private.is_platform_admin());

create policy "workspaces_delete_owner_or_platform_admin"
on public.workspaces for delete
to authenticated
using (owner_id = (select auth.uid()) or private.is_platform_admin());

create policy "financial_entities_select_workspace_member"
on public.financial_entities for select
to authenticated
using (
  private.is_platform_admin()
  or exists (
    select 1 from public.workspace_members wm
    where wm.workspace_id = financial_entities.workspace_id
      and wm.user_id = (select auth.uid())
      and wm.status = 'active'
      and coalesce((wm.permissions->'finance'->>'view')::boolean, true)
      and (
        financial_entities.entity_type <> 'investments'
        or wm.role in ('owner','admin')
        or coalesce((wm.permissions->'investments'->>'view')::boolean, false)
      )
  )
);

