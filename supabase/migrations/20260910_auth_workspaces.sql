create extension if not exists pgcrypto;

create schema if not exists private;

create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  email text,
  display_name text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.workspaces (
  id uuid primary key default gen_random_uuid(),
  name text not null check (char_length(trim(name)) between 2 and 120),
  kind text not null default 'personal' check (kind in ('personal','client','business')),
  owner_id uuid not null references auth.users(id) on delete restrict,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.workspace_members (
  id uuid primary key default gen_random_uuid(),
  workspace_id uuid not null references public.workspaces(id) on delete cascade,
  user_id uuid not null references auth.users(id) on delete cascade,
  role text not null default 'viewer' check (role in ('owner','admin','editor','viewer','custom')),
  permissions jsonb not null default '{"finance":{"view":true,"write":false},"open_finance":{"view":false,"manage":false},"investments":{"view":false,"write":false},"users":{"manage":false}}'::jsonb,
  status text not null default 'active' check (status in ('active','invited','suspended')),
  invited_by uuid references auth.users(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (workspace_id, user_id)
);

create table if not exists public.financial_entities (
  id uuid primary key default gen_random_uuid(),
  workspace_id uuid not null references public.workspaces(id) on delete cascade,
  entity_type text not null check (entity_type in ('transactions','accounts','cards','categories','investments','settings')),
  local_id text not null,
  data jsonb not null default '{}'::jsonb,
  version bigint not null default 1,
  deleted boolean not null default false,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (workspace_id, entity_type, local_id)
);

create index if not exists idx_financial_entities_workspace_type_updated
  on public.financial_entities(workspace_id, entity_type, updated_at desc);

create table if not exists public.audit_log (
  id bigint generated by default as identity primary key,
  workspace_id uuid references public.workspaces(id) on delete cascade,
  actor_user_id uuid references auth.users(id) on delete set null,
  action text not null,
  entity_type text,
  entity_id text,
  details jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);

create index if not exists idx_audit_log_workspace_created
  on public.audit_log(workspace_id, created_at desc);

create or replace function private.is_platform_admin()
returns boolean
language sql
stable
security invoker
set search_path = pg_catalog
as $$
  select coalesce(((select auth.jwt())->'app_metadata'->>'platform_admin')::boolean, false)
$$;

create or replace function private.default_owner_permissions()
returns jsonb
language sql
immutable
security invoker
set search_path = pg_catalog
as $$
  select '{"finance":{"view":true,"write":true},"open_finance":{"view":true,"manage":true},"investments":{"view":true,"write":true},"users":{"manage":true}}'::jsonb
$$;

create or replace function private.handle_workspace_insert()
returns trigger
language plpgsql
security definer
set search_path = pg_catalog, public, private
as $$
begin
  insert into public.workspace_members(workspace_id, user_id, role, permissions, status)
  values (new.id, new.owner_id, 'owner', private.default_owner_permissions(), 'active')
  on conflict (workspace_id, user_id) do update
    set role = 'owner', permissions = private.default_owner_permissions(), status = 'active', updated_at = now();
  return new;
end;
$$;

create or replace function private.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = pg_catalog, public, private
as $$
declare
  workspace_name text;
begin
  insert into public.profiles(id, email, display_name)
  values (
    new.id,
    new.email,
    coalesce(nullif(new.raw_user_meta_data->>'display_name',''), split_part(coalesce(new.email,'Usuário'),'@',1))
  )
  on conflict (id) do nothing;

  workspace_name := coalesce(nullif(new.raw_user_meta_data->>'display_name',''), split_part(coalesce(new.email,'Usuário'),'@',1)) || ' — Pessoal';
  insert into public.workspaces(name, kind, owner_id)
  values (workspace_name, 'personal', new.id);
  return new;
end;
$$;

revoke all on function private.is_platform_admin() from public, anon;
revoke all on function private.default_owner_permissions() from public, anon, authenticated;
revoke all on function private.handle_workspace_insert() from public, anon, authenticated;
revoke all on function private.handle_new_user() from public, anon, authenticated;
grant execute on function private.is_platform_admin() to authenticated;

DROP TRIGGER IF EXISTS trg_workspace_owner_membership ON public.workspaces;
create trigger trg_workspace_owner_membership
after insert on public.workspaces
for each row execute function private.handle_workspace_insert();

DROP TRIGGER IF EXISTS trg_auth_user_bootstrap ON auth.users;
create trigger trg_auth_user_bootstrap
after insert on auth.users
for each row execute function private.handle_new_user();

